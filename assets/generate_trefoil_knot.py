"""Writes trefoil_knot.obj: a tube around a trefoil knot, as a Wavefront OBJ mesh.

Run with Python 3.6 or later: python3 generate_trefoil_knot.py
The output is deterministic: rerunning it on the same platform reproduces the
committed file, while another platform's math library may change the last of
the six printed decimals here and there.

The knot is the curve (sin t + 2 sin 2t, cos t - 2 cos 2t, -sin 3t). The tube
follows its Frenet frame, which closes up after one loop because the curve's
curvature never vanishes. Faces are quads, wound counter-clockwise seen from
outside the tube.
"""

import math
from pathlib import Path

SEGMENTS = 384  # Steps along the knot.
SIDES = 40  # Steps around the tube.
TUBE_RADIUS = 0.45


def curve(t):
    return (math.sin(t) + 2 * math.sin(2 * t),
            math.cos(t) - 2 * math.cos(2 * t),
            -math.sin(3 * t))


def derivative(t):
    return (math.cos(t) + 4 * math.cos(2 * t),
            -math.sin(t) + 4 * math.sin(2 * t),
            -3 * math.cos(3 * t))


def second_derivative(t):
    return (-math.sin(t) - 8 * math.sin(2 * t),
            -math.cos(t) + 8 * math.cos(2 * t),
            9 * math.sin(3 * t))


def cross(a, b):
    return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])


def dot(a, b):
    return sum(x * y for x, y in zip(a, b))


def normalized(v):
    length = math.sqrt(dot(v, v))
    return tuple(x / length for x in v)


def frame(t):
    tangent = normalized(derivative(t))
    binormal = normalized(cross(derivative(t), second_derivative(t)))
    normal = cross(binormal, tangent)
    return tangent, normal, binormal


def vertices():
    for segment in range(SEGMENTS):
        t = 2 * math.pi * segment / SEGMENTS
        center = curve(t)
        _, normal, binormal = frame(t)
        for side in range(SIDES):
            angle = 2 * math.pi * side / SIDES
            offset = tuple(TUBE_RADIUS * (math.cos(angle) * n + math.sin(angle) * b)
                           for n, b in zip(normal, binormal))
            yield tuple(c + o for c, o in zip(center, offset))


def index(segment, side):
    """1-based OBJ index of a vertex, wrapping around both loops."""
    return (segment % SEGMENTS) * SIDES + (side % SIDES) + 1


def faces():
    for segment in range(SEGMENTS):
        for side in range(SIDES):
            # (tangent x around) points into the tube, so this order points out.
            yield (index(segment, side), index(segment, side + 1),
                   index(segment + 1, side + 1), index(segment + 1, side))


def check_winding(points, quads):
    """Every face normal must point away from the knot curve."""
    for quad in quads:
        a, b, c = (points[i - 1] for i in quad[:3])
        face_normal = cross(tuple(y - x for x, y in zip(a, b)), tuple(y - x for x, y in zip(a, c)))
        segment = (quad[0] - 1) // SIDES
        outward = tuple(p - q for p, q in zip(a, curve(2 * math.pi * segment / SEGMENTS)))
        if dot(face_normal, outward) <= 0:
            raise RuntimeError(f"face {quad} is wound inwards")


def main():
    points = list(vertices())
    quads = list(faces())
    check_winding(points, quads)
    lines = [f"# Trefoil knot tube, {len(points)} vertices and {len(quads)} quads.",
             "# Generated by generate_trefoil_knot.py; do not edit by hand."]
    lines += [f"v {x:.6f} {y:.6f} {z:.6f}" for x, y, z in points]
    lines += ["f " + " ".join(str(i) for i in quad) for quad in quads]
    output = Path(__file__).with_name("trefoil_knot.obj")
    with open(output, "w", encoding="ascii", newline="\n") as file:
        file.write("\n".join(lines) + "\n")
    print(f"wrote {output}")


if __name__ == "__main__":
    main()
